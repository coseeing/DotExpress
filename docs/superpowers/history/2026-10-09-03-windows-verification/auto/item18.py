import sys, os, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dx, docs as D
EXE, d = r"D:\dxtest\N\DotExpress.exe", r"D:\dxtest\auto18"
app, w = dx.launch(EXE, d)
print("start docs:", D.docs(w), D.ws_state(d))
print("add Alpha:", D.add(app, w, "Alpha"))
D.set_input(w, "Alpha body 中文內容 123")
print("docs:", D.docs(w), "title:", w.window_text())
print("close:", D.close(app, w))
print("disk:", D.ws_state(d))
app, w = dx.launch(EXE, d, fresh=False)
D.select(w, "Alpha")
print("reopen Alpha input:", repr(D.get_input(w)))
print("rename -> alpha:", D.rename(app, w, "alpha"))
print("docs:", D.docs(w), "disk:", D.ws_state(d))
print("close:", D.close(app, w))
app, w = dx.launch(EXE, d, fresh=False)
print("after restart docs:", D.docs(w))
D.select(w, "alpha")
print("alpha input:", repr(D.get_input(w)))
print("disk:", D.ws_state(d))
before = D.ws_state(d)
r = D.add(app, w, "ALPHA"); print("add ALPHA:", r); D.cancel_open(app, w)
print("disk diff:", D.diff(before, D.ws_state(d)), "docs:", D.docs(w))
D.select(w, "new")
r = D.rename(app, w, "Alpha"); print("rename new -> Alpha:", r); D.cancel_open(app, w)
print("disk diff:", D.diff(before, D.ws_state(d)), "docs:", D.docs(w))
print("close:", D.close(app, w))
print("final disk:", D.ws_state(d))
