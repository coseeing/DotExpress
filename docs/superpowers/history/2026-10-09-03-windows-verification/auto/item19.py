import sys, os, time, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dx, docs as D
EXE, d = r"D:\dxtest\N\DotExpress.exe", r"D:\dxtest\auto18"
ws = os.path.join(d, "workspace")
LOCK = os.path.join(os.path.dirname(os.path.abspath(__file__)), "lock.py")
dx.kill_under(d)
for share in ("r", "rw"):
	print(f"== 19 share={share}")
	dx.kill_under(d); app, w = dx.launch(EXE, d, fresh=False)
	D.select(w, "alpha")
	before = D.ws_state(d)
	z = subprocess.Popen([sys.executable, LOCK, os.path.join(ws, "alpha.dep"), "120", share])
	time.sleep(2)
	print("rename alpha->Alpha while locked:", D.rename(app, w, "Alpha"))
	D.cancel_open(app, w)
	print("list:", D.docs(w), "diff:", D.diff(before, D.ws_state(d)), "files:", os.listdir(ws))
	subprocess.run(["taskkill", "/T", "/F", "/PID", str(z.pid)], capture_output=True); time.sleep(1)
	print("close:", D.close(app, w))
	dx.kill_under(d); app, w = dx.launch(EXE, d, fresh=False)
	print("after restart:", D.docs(w), D.ws_state(d), os.listdir(ws))
	if "Alpha" in D.docs(w):
		D.select(w, "Alpha"); print("undo rename:", D.rename(app, w, "alpha"))
	print("close:", D.close(app, w))
print("== 20 read-only")
dx.kill_under(d); app, w = dx.launch(EXE, d, fresh=False)
subprocess.run(["attrib", "+r", os.path.join(ws, "alpha.dep")])
D.select(w, "alpha")
print("rename alpha->Alpha with +r:", D.rename(app, w, "Alpha"))
D.cancel_open(app, w)
print("list:", D.docs(w), "state:", D.ws_state(d))
print("attrib:", subprocess.run(["cmd", "/c", "attrib", os.path.join(ws, "*")], capture_output=True, text=True).stdout)
print("close:", D.close(app, w))
subprocess.run(["attrib", "-r", os.path.join(ws, "alpha.dep")])
print("final:", D.ws_state(d), os.listdir(ws))
